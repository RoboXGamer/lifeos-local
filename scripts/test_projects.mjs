import { strict as assert } from 'node:assert';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { collectProject } from '../server/project-collector.mjs';
import { openStorage } from '../server/storage.mjs';
import { installStorageAdapter } from '../src/local/db.ts';
import { api, ensureProfile } from '../src/local/api.ts';
import { data, reload } from '../src/local/store.ts';
import { setProjectCollector } from '../src/local/projects.ts';

const directory = mkdtempSync(join(tmpdir(),'lifeos-projects-'));
const repo = join(directory,'repo'); mkdirSync(repo); mkdirSync(join(repo,'src'));
writeFileSync(join(repo,'README.md'),'# Revival fixture\nOriginal setup and intended outcome.\napi_key=SECRET_CAPTURE_MUST_REDACT');
writeFileSync(join(repo,'package.json'),JSON.stringify({name:'revival-fixture',scripts:{build:'node -e "require(\'fs\').writeFileSync(\'SCRIPT_RAN\',\'bad\')"'},dependencies:{example:'0.0.1'}}));
writeFileSync(join(repo,'src','main.ts'),'// TODO: ship one small feature\nexport const useful = true;');
writeFileSync(join(repo,'.env'),'SECRET_ENV_MUST_NEVER_CAPTURE=secret');
writeFileSync(join(repo,'src','private.ts'),'// PRIVATE_SOURCE_EXCLUDED');
execFileSync('git',['init',repo],{windowsHide:true,stdio:'ignore'});
execFileSync('git',['-C',repo,'add','.'],{windowsHide:true,stdio:'ignore'});
execFileSync('git',['-C',repo,'-c','user.name=LifeOS Test','-c','user.email=lifeos-test@example.invalid','commit','-m','test: fixture'],{windowsHide:true,stdio:'ignore'});
const collection = await collectProject({repositories:[repo],exclusions:['private.ts'],retentionDays:365});
assert(collection.some(s=>s.metadata.category==='manifest'));
assert(collection.some(s=>s.metadata.category==='todos'&&s.content.includes('ship one small feature')));
assert(!JSON.stringify(collection).includes('SECRET_CAPTURE_MUST_REDACT'));
assert(!JSON.stringify(collection).includes('SECRET_ENV_MUST_NEVER_CAPTURE'));
assert(!JSON.stringify(collection).includes('PRIVATE_SOURCE_EXCLUDED'));
assert(!existsSync(join(repo,'SCRIPT_RAN')),'Collector must never run repository scripts');
assert((await collectProject({repositories:[join(directory,'missing')],exclusions:[],retentionDays:365}))[0].missing===1);

const migrations = readdirSync('src-tauri/migrations').filter(n=>/^\d+.*\.sql$/.test(n)).sort().map(name=>[Number(name.split('_')[0]),name,readFileSync(join('src-tauri/migrations',name),'utf8')]);
const storage = openStorage(join(directory,'lifeos.db'),migrations); installStorageAdapter(storage); await ensureProfile(); setProjectCollector(collectProject);
const workspaceId = data.profile.activeWorkspaceId;
const input=title=>({workspaceId,title,type:'Note',status:null,priority:null,dueDate:null,amount:null,financialState:null,description:null,parentId:null,areaId:null,tags:[]});
const root = await api.items.create(input('Project family'));
const projectId = await api.projects.create({workspaceId,itemId:root,name:'Project memory fixture',goal:'Ship one useful feature',audience:'A real user',valueStatement:'They need the existing implementation',status:'paused',settings:{repositories:[repo],exclusions:['private.ts'],retentionDays:365}});
const args = {workspaceId,projectId};
assert.equal(api.projects.resume(args).nextActionKind,'suggestion');
assert.equal(api.projects.report(args).recommendation,'review');
await api.projects.checkpoint({...args,did:'Finished auth',failed:'Build failed because package X was unavailable',whyStopped:'Needed a decision',next:'Replace package X and rerun the documented build',branch:'resume',commit:'abc123'});
const old=Date.now()-45*86400000;
storage.db.prepare('UPDATE projectCheckpoints SET createdAt=? WHERE projectId=?').run(old,projectId); await reload();
const brief=api.projects.resume(args);
assert.equal(brief.recordedAt,old);
assert.equal(brief.lastWork,'Finished auth'); assert(brief.failedAttempts.includes('package X')); assert(brief.nextAction.includes('Replace package X')); assert.equal(brief.nextActionKind,'recorded');
await api.projects.scan(args);
const report=api.projects.report(args);
assert.equal(report.recommendation,'revive'); assert(report.reusable.length>=2); assert(report.uncertain.some(x=>x.includes('unknown'))); assert(report.readiness.includes('unverified'));
const tasks=await api.projects.acceptPlan({...args,reportKey:report.reportKey});
const twice=await api.projects.acceptPlan({...args,reportKey:report.reportKey});
assert.deepEqual(tasks,twice); assert(tasks.every(id=>data.items.some(i=>i._id===id&&i.parentId===root)));
assert(!existsSync(join(repo,'SCRIPT_RAN')));
await api.projects.addSource({...args,kind:'link',locator:'https://example.com/docs?token=DO_NOT_STORE',label:'Selected docs',content:'A manual note'});
const link=api.projects.sources(args).find(s=>s.kind==='link'); assert(!link.locator.includes('DO_NOT_STORE'));
await api.projects.addSource({...args,kind:'link',locator:'https://example.com/docs?token=DO_NOT_STORE',label:'Selected docs',content:'An updated manual note'});
const revisions=api.projects.sources({...args,history:true}).filter(s=>s.kind==='link');
assert.equal(revisions.length,2,'Changed evidence preserves a previous source revision');
storage.db.prepare('UPDATE projectSources SET capturedAt=? WHERE projectId=? AND kind=?').run(Date.now(),projectId,'link'); await reload();
assert.equal(api.projects.sources(args).find(s=>s.kind==='link').content,'An updated manual note','Revision order remains deterministic when capture times match');
await api.projects.removeSource({...args,sourceId:link._id}); assert(!api.projects.sources(args).some(s=>s.kind==='link'));
assert(!api.projects.sources({...args,history:true}).some(s=>s.kind==='link'),'Delete removes all source revisions');
unlinkSync(join(repo,'README.md')); await api.projects.scan(args);
const removedReadme=api.projects.sources(args).find(s=>s.metadata.category==='readme');
assert(removedReadme?.missing===1,'A disappeared source is explicitly marked missing');
assert(api.projects.sources({...args,history:true}).some(s=>s.metadata.category==='readme'&&!s.missing),'Old source revision remains available');
await assert.rejects(api.projects.acceptPlan({...args,reportKey:report.reportKey}),/evidence changed/,'Accepting a stale report requires review');
const other=await api.workspaces.create({name:'Other project workspace'});
assert.throws(()=>api.projects.resume({workspaceId:other,projectId}),/not found/);
await assert.rejects(api.projects.checkpoint({workspaceId:other,projectId,did:'wrong',next:'wrong'}),/not found/);
await api.projects.remove({...args,confirmation:'Project memory fixture'});
assert(!data.projects.some(p=>p._id===projectId)); assert(data.items.some(i=>i._id===root)); assert(existsSync(repo));
storage.db.close();
console.log('Project read-only collector, source redaction, 45-day resume, revival evidence, dedupe, isolation, and memory removal passed');
