import { strict as assert } from 'node:assert';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openStorage } from '../server/storage.mjs';
import { installStorageAdapter } from '../src/local/db.ts';
import { api, ensureProfile } from '../src/local/api.ts';
import { data } from '../src/local/store.ts';
import { readMigrations } from './test-helpers.mjs';

const dir = mkdtempSync(join(tmpdir(), 'lifeos-templates-'));
const storage = openStorage(join(dir, 'lifeos.db'), readMigrations());
installStorageAdapter(storage);
await ensureProfile();
const workspaceId = data.profile.activeWorkspaceId;
const request = { workspaceId, templateId: 'starter:client', startDate: '2026-10-29', variables: { client: 'Acme', amount: '25000' } };
const preview = api.templates.preview(request);
assert.equal(data.items.length, 0, 'preview must not write');
assert.equal(preview.items[2].amount, 25000);
assert.equal(preview.items[2].financialState, 'Expected');
assert.equal(preview.items[2].dueDate, '2026-10-30');
assert.throws(() => api.templates.preview({ ...request, variables: {} }), /Fill in client/);
assert.throws(() => api.templates.preview({ ...request, startDate: '2026-02-30' }), /valid date/);
const id = await api.templates.apply(request);
const children = data.items.filter(i => i.parentId === id);
assert.equal(children.length, 3);
assert(children.every(i => i.workspaceId === workspaceId));
const saved = await api.templates.saveFamily({ workspaceId, itemId: id, name: 'Acme process', startDate: request.startDate });
const definition = structuredClone(api.templates.list({ workspaceId }).find(t => t._id === saved).definition);
definition.entries[0].title = 'Changed {{project}}';
await api.templates.save({ workspaceId, templateId: saved, definition, expectedVersion: 1 });
assert.equal(data.items.find(i => i._id === id).title, 'Acme onboarding', 'template edits do not alter instances');
assert.equal(data.templates[0].version, 2);
await assert.rejects(api.templates.save({ workspaceId, templateId: saved, definition, expectedVersion: 1 }), /changed/);
const before = data.items.length;
storage.db.exec("CREATE TRIGGER fail_template BEFORE INSERT ON items WHEN NEW.title LIKE '%scope and payment%' BEGIN SELECT RAISE(ABORT, 'injected failure'); END");
await assert.rejects(api.templates.apply(request), /injected failure/);
assert.equal(storage.db.prepare('SELECT COUNT(*) AS n FROM items').get().n, before);
assert.equal(storage.db.prepare('SELECT COUNT(*) AS n FROM templateInstances').get().n, 1);
storage.db.exec('DROP TRIGGER fail_template');
const otherWorkspace = await api.workspaces.create({ name: 'Other' });
assert.throws(() => api.templates.preview({ ...request, workspaceId: otherWorkspace, templateId: saved }), /not found/);
await assert.rejects(api.templates.remove({ workspaceId: otherWorkspace, templateId: saved }), /not found/);
await api.templates.remove({ workspaceId, templateId: saved });
assert.equal(data.items.length, before, 'deleting a template preserves instances');
storage.db.close();
const reopened = openStorage(join(dir, 'lifeos.db'), readMigrations());
assert.equal(reopened.db.prepare('SELECT COUNT(*) AS n FROM templateInstances').get().n, 1);
reopened.db.close();
console.log('Templates: preview, variables, relative dates, family, versioning, rollback, workspace isolation and restart passed');
