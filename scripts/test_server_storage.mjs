import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { strict as assert } from 'node:assert';
import { openStorage } from '../server/storage.mjs';
import { installStorageAdapter } from '../src/local/db.ts';
import { api, ensureProfile } from '../src/local/api.ts';
import { data } from '../src/local/store.ts';
import { readMigrations } from './test-helpers.mjs';

const dir = mkdtempSync(join(tmpdir(), 'lifeos-server-test-'));
const migrations = readMigrations();
const storage = openStorage(join(dir, 'lifeos.db'), migrations);
installStorageAdapter(storage);
await ensureProfile();
const workspaceId = data.profile.activeWorkspaceId;
const id = await api.items.quickCapture({ workspaceId, title: 'Server capture' });
assert.equal(api.items.get({ itemId: id }).title, 'Server capture');
assert.equal(api.items.search({ workspaceId, searchTerm: 'capture' }).length, 1);
await assert.rejects(api.items.setTaskDone({ itemId: id, done: true }));
await api.items.quickCapture({ workspaceId, title: 'After failed mutation' });
assert.equal(api.items.list({ workspaceId }).length, 2);
const input = (title, parentId = null, tags = []) => ({ title, parentId, tags, areaId: null, type: 'Task', status: 'Todo', priority: null, dueDate: null, amount: null, financialState: null, description: null });
const parent = await api.items.create({ workspaceId, ...input('parent', null, ['waiting']) });
const child = await api.items.create({ workspaceId, ...input('child', parent) });
storage.db.exec("CREATE TRIGGER fail_tag BEFORE INSERT ON itemTags BEGIN SELECT RAISE(ABORT, 'injected tag failure'); END");
await assert.rejects(api.items.update({ itemId: parent, ...input('changed', null, ['urgent']) }));
assert.equal(storage.db.prepare('SELECT title FROM items WHERE _id = ?').get(parent).title, 'parent');
assert.equal(storage.db.prepare('SELECT COUNT(*) AS count FROM itemTags WHERE itemId = ?').get(parent).count, 1);
storage.db.exec('DROP TRIGGER fail_tag');
storage.db.exec("CREATE TRIGGER fail_child BEFORE UPDATE ON items WHEN OLD.title = 'child' BEGIN SELECT RAISE(ABORT, 'injected child failure'); END");
await assert.rejects(api.items.setArchived({ itemId: parent, archived: true }));
assert(storage.db.prepare('SELECT archived FROM items WHERE _id IN (?, ?)').all(parent, child).every(row => row.archived === 0));
storage.db.exec('DROP TRIGGER fail_child');
await api.items.setArchived({ itemId: parent, archived: true });
storage.db.exec("CREATE TRIGGER fail_delete BEFORE DELETE ON items WHEN OLD.title = 'parent' BEGIN SELECT RAISE(ABORT, 'injected delete failure'); END");
await assert.rejects(api.items.remove({ itemId: parent, confirmation: 'parent' }));
assert.equal(storage.db.prepare('SELECT COUNT(*) AS count FROM itemTags WHERE itemId = ?').get(parent).count, 1);
assert.equal(storage.db.prepare('SELECT COUNT(*) AS count FROM items WHERE _id IN (?, ?)').get(parent, child).count, 2);
storage.db.exec('DROP TRIGGER fail_delete');
await Promise.all(Array.from({ length: 8 }, (_, i) => api.items.quickCapture({ workspaceId, title: `concurrent ${i}` })));
assert.equal(storage.db.prepare("SELECT COUNT(*) AS count FROM items WHERE title LIKE 'concurrent %'").get().count, 8);
assert.equal(data.items.filter(item => item.title.startsWith('concurrent ')).length, 8);
storage.db.close();
const reopened = openStorage(join(dir, 'lifeos.db'), migrations);
assert.equal(reopened.db.prepare('SELECT COUNT(*) AS count FROM items').get().count, 12);
reopened.db.close();
assert.throws(() => openStorage(join(dir, 'lifeos.db'), [[1, 'create_todos', migrations[0][2] + ' '], ...migrations.slice(1)]), /checksum mismatch/);
console.log('Server migrations, validation, rollback, concurrent writes and persistence passed');
